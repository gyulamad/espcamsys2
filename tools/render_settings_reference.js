'use strict';

// render_settings_reference.js — turns the settings tables of the camera (recorder), the detector and the relay into
// docs/SETTINGS_REFERENCE.md (key, label, default, tier, apply, category). Used by tools/gen_settings_reference.sh;
// no file system or network in the rendering itself (render), so it is unit tested: tests/node/test_settings_reference.js.
//
//   node tools/render_settings_reference.js SCHEMA.json     prints the Markdown
//
// SCHEMA.json is { "recorder": {"keys": [...]}, "detector": {"keys": [...]}, "relay": [rows] }: the first two are the
// dumps of tools/dump_device_schema.cpp (device keys), the third what tools/dump_relay_schema.js prints (rows).
//
// Deterministic on purpose (the rows keep the order of the firmware's own table; no date, no host): the CI check
// regenerates this and compares it byte for byte with the committed file.

const fs = require('fs');

const DASH = '—';   // "nothing here": no default, no label, no tier yet (see the legend in HEADER)
const COLUMNS = ['Key', 'Label', 'Default', 'Tier', 'Apply', 'Category'];

const HEADER = `<!-- GENERATED by tools/gen_settings_reference.sh from the settings tables of ESP32_CAM_Recorder, ESP32_CAM_TFLite_Person and nodejs/camera-relay — do not edit; run the script after changing a table. -->

# Settings reference

Every setting of the camera (recorder), the detector and the relay, straight from the tables the firmware and the relay
use. \`./run_tests.sh\` fails when this file is out of date.

- **Default** — what is used while nothing is stored (the former hard-coded value). \`${DASH}\` = no default: an
  identity or locked value that stays required (WiFi, \`SERVER_HOST\`, ports, \`CAMERA_ID\`, \`API_KEY\`, ...), or one that
  has not moved into the defaults table yet. A secret is never listed with a value.
- **Tier** — Basic, Advanced or Expert: how deep the settings page puts the row.
- **Apply** — \`live\`: takes effect at once; \`reboot\`: only after the board reboots (the relay: restarts).
`;

// The text of one table cell: it must stay on one line and not break the table.
function cell(text) {
  return String(text).replace(/\r?\n/g, ' ').replace(/\\/g, '\\\\').replace(/\|/g, '\\|');
}

// A default as a code span: "" for an empty text; a value that holds a backtick cannot be in a code span, so it is plain text.
function defaultCell(value) {
  if (value === null || value === undefined) return DASH;
  const text = String(value);
  if (text === '') return '`""`';
  if (text.indexOf('`') !== -1) return cell(text);
  return '`' + cell(text) + '`';
}

function plainCell(value) {
  return value === null || value === undefined || value === '' ? DASH : cell(value);
}

// One firmware key (a dump entry of dump_device_schema.cpp) -> the common row. A secret never carries its default.
function deviceRow(k) {
  return {
    key: k.name,
    label: k.label,
    default: k.kind === 'secret' ? null : k.default,
    tier: k.tier,
    apply: k.apply,
    category: k.category,
  };
}

function tableRow(r) {
  return '| `' + cell(r.key) + '` | ' + [plainCell(r.label), defaultCell(r.default), plainCell(r.tier), plainCell(r.apply), plainCell(r.category)].join(' | ') + ' |';
}

// "N settings: M with a default, K without" — also the real counts the design boards (T10) need.
function countLine(rows) {
  const withDefault = rows.filter((r) => r.default !== null && r.default !== undefined).length;
  return rows.length + ' settings: ' + withDefault + ' with a default, ' + (rows.length - withDefault) + ' without.';
}

function section(title, source, rows) {
  const lines = ['## ' + title, '', 'Source: ' + source + '. ' + countLine(rows), ''];
  if (rows.length === 0) return lines.concat(['_No settings._', '']).join('\n');
  lines.push('| ' + COLUMNS.join(' | ') + ' |', '|' + COLUMNS.map(() => ' --- ').join('|') + '|');
  rows.forEach((r) => lines.push(tableRow(r)));
  lines.push('');
  return lines.join('\n');
}

function render(schema) {
  // TODO(T5a, T5b, T5c): the detector's table has no defaulted keys yet, so its rows are all "no default" until those
  //   tasks fill PERSON_META; nothing to change here when they do.
  // TODO(T6a): the relay section lists the values in lib/sysconfig.js today; the values T6a moves in (config.js or
  //   environment only) appear by themselves once tools/dump_relay_schema.js reads the new table.
  return HEADER + '\n' + [
    section('Camera (ESP32_CAM_Recorder)', '`Arduino/ESP32_CAM_Recorder/settings_schema.h`', schema.recorder.keys.map(deviceRow)),
    section('Detector (ESP32_CAM_TFLite_Person)', '`Arduino/ESP32_CAM_TFLite_Person/settings_schema.h`', schema.detector.keys.map(deviceRow)),
    section('Relay (nodejs/camera-relay)', '`nodejs/camera-relay/lib/sysconfig.js` (see `tools/dump_relay_schema.js`)', schema.relay),
  ].join('\n');
}

if (require.main === module) {
  if (process.argv.length !== 3) {
    process.stderr.write('usage: node tools/render_settings_reference.js SCHEMA.json\n');
    process.exit(2);
  }
  process.stdout.write(render(JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))));
}

module.exports = { render, cell, defaultCell, deviceRow, countLine };
