#!/usr/bin/env bash
# Rewrites php/cameras/lib/device_schema.php from the firmware's settings table
# (Arduino/ESP32_CAM_Recorder/settings_schema.h). Run after changing that table.
# With --check, changes nothing and fails if the file is out of date (run_tests.sh does this).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/php/cameras/lib/device_schema.php"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
g++ -std=c++11 -Wall -Wextra -o "$TMP/dump" "$ROOT/tools/dump_device_schema.cpp"
# A PHP file (not .json): deploy.sh ships lib/*.php, and a .json in the web root would be served without the login.
{
    echo '<?php'
    echo '// GENERATED by tools/gen_device_schema.sh from Arduino/ESP32_CAM_Recorder/settings_schema.h — do not edit.'
    echo '// The Recorder'"'"'s settings (kind, limits, conditions, help text, which are locked) for the camera settings page.'
    echo 'return json_decode(<<<'"'"'JSON'"'"
    "$TMP/dump"
    echo 'JSON, true);'
} > "$TMP/schema.php"
if [ "${1:-}" = "--check" ]; then
    if cmp -s "$TMP/schema.php" "$OUT"; then echo "device_schema.php is up to date"; exit 0; fi
    echo "FAIL: php/cameras/lib/device_schema.php is out of date — run tools/gen_device_schema.sh" >&2
    exit 1
fi
cp "$TMP/schema.php" "$OUT"
echo "wrote $OUT"
